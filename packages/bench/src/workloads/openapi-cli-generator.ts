/** A group's specifications generated in turn under its author configuration: every emitted file and every
 * diagnostic, or the refusal. */
const generated = (row: (typeof ROWS)[number]): Workload["run"] => {
	const documents = Arr.map(row.specs, (spec) => encoder.encode(jsonTextOf(spec)))
	return Effect.gen(function* () {
		const spec = yield* decodeDocumentUri("file:///bench/openapi.json")
		const configDocument = yield* decodeDocumentUri("file:///bench/author-config.json")
		const config = yield* decodeAuthorConfig(row.config, { document: configDocument })
		const runs = yield* Effect.forEach(documents, (bytes) =>
			Effect.result(pipeline(bytes, spec, config, configDocument))
		)
		return () => Formatter.format(runs)
	}).pipe(Effect.orDie)
}

